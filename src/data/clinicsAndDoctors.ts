// Helper to get clinics by city or specialty
export function getClinicsByCity(city?: MetroCity): Clinic[] {
  if (!city) return CLINICS;
  return CLINICS.filter((c) => c.city.toLowerCase() === city.toLowerCase());
}

export function getDoctorsBySpecialtyAndCity(specialty?: string, city?: MetroCity): Doctor[] {
  let list = DOCTORS;
  if (specialty && specialty !== 'All') {
    list = list.filter((d) => d.specialty.toLowerCase() === specialty.toLowerCase());
  }
  if (city) {
    list = list.filter((d) => d.city.toLowerCase() === city.toLowerCase());
  }
  return list;
}

